// Builds the registry into public/r and regenerates examples/__index__.tsx
// and registry/blocks/__index__.tsx.
//
// registry.json is written against http://localhost:3000 (homepage and the
// registryDependencies URLs). The JSON the CLI downloads must point at the
// site serving it, so the URLs are swapped for getSiteUrl() before building.

import { execFileSync } from "node:child_process"
import { promises as fs } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { getSiteUrl, REGISTRY_URL_PLACEHOLDER } from "../lib/site-url.mjs"

const root = fileURLToPath(new URL("..", import.meta.url))

async function buildExamplesIndex() {
  const dir = path.join(root, "examples")
  const files = (await fs.readdir(dir))
    .filter((file) => file.endsWith(".tsx") && !file.startsWith("__"))
    .sort()

  const entries = files.map((file) => {
    const name = file.replace(/\.tsx$/, "")
    return `  "${name}": {
    name: "${name}",
    filePath: "examples/${file}",
    component: () => import("./${name}"),
  },`
  })

  const content = `// This file is autogenerated by scripts/build-registry.mjs.
// Do not edit this file directly.

export const ExamplesIndex: Record<
  string,
  {
    name: string
    filePath: string
    component: () => Promise<Record<string, unknown>>
  }
> = {
${entries.join("\n")}
}
`

  await fs.writeFile(path.join(dir, "__index__.tsx"), content)
  console.log(`examples: indexed ${files.length} examples`)
}

// Each block's page.tsx, loaded by the /view/[name] route the Blocks page
// shows in an iframe.
async function buildBlocksIndex() {
  const source = JSON.parse(
    await fs.readFile(path.join(root, "registry.json"), "utf8")
  )
  const blocks = source.items.filter((item) => item.type === "registry:block")

  const entries = blocks.map((block) => {
    const page = block.files.find((file) => file.type === "registry:page")
    const file = page.path.replace(/^registry\/blocks\//, "")
    return `  "${block.name}": {
    name: "${block.name}",
    component: () => import("./${file.replace(/\.tsx$/, "")}"),
  },`
  })

  const content = `// This file is autogenerated by scripts/build-registry.mjs.
// Do not edit this file directly.

export const BlocksIndex: Record<
  string,
  {
    name: string
    component: () => Promise<{ default: React.ComponentType }>
  }
> = {
${entries.join("\n")}
}
`

  await fs.writeFile(path.join(root, "registry/blocks/__index__.tsx"), content)
  console.log(`blocks: indexed ${blocks.length} blocks`)
}

// The `all` item installs the whole library in one command: the style, every
// component and hook. Blocks are left out: they write demo pages into the
// user's app. Generated here so it can't drift from registry.json.
//
// It is a registry:style, not a registry:item: the CLI only overwrites a
// project's existing theme variables when the item named on the command line
// is a style, so a plain item would leave shadcn's default colors in place.
const ALL_ITEM_TYPES = ["registry:style", "registry:ui", "registry:hook"]

function withAllItem(registry) {
  const items = registry.items.filter((item) =>
    ALL_ITEM_TYPES.includes(item.type)
  )

  return {
    ...registry,
    items: [
      ...registry.items,
      {
        name: "all",
        type: "registry:style",
        title: "All",
        description: "The style and every component and hook in the library.",
        registryDependencies: items.map(
          (item) => `${REGISTRY_URL_PLACEHOLDER}/r/${item.name}.json`
        ),
      },
    ],
  }
}

async function buildRegistry() {
  const url = getSiteUrl()
  const registry = JSON.parse(
    await fs.readFile(path.join(root, "registry.json"), "utf8")
  )
  if (registry.items.some((item) => item.name === "all")) {
    throw new Error("registry.json must not define `all`; it is generated.")
  }
  const source = JSON.stringify(withAllItem(registry), null, 2)
  const tmp = path.join(root, ".registry.json")

  await fs.writeFile(tmp, source.replaceAll(REGISTRY_URL_PLACEHOLDER, url))

  try {
    console.log(`registry: building for ${url}`)
    execFileSync("shadcn", ["build", tmp, "--output", "public/r"], {
      cwd: root,
      stdio: "inherit",
    })
  } finally {
    await fs.rm(tmp, { force: true })
  }
}

await buildExamplesIndex()
await buildBlocksIndex()
await buildRegistry()
